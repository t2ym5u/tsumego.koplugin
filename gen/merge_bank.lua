-- ---------------------------------------------------------------------------
-- gen/merge_bank.lua -- merges gen_bank.lua outputs into problems.lua.
--     luajit gen/merge_bank.lua [--retree] <out/problems.lua> <part1.lua> [part2.lua ...]
-- Drops duplicates (the same frame, or its mirror image across the corner's
-- diagonal, with the same task), keys each problem by its generator seed
-- (stable, so saved progress survives a regeneration that keeps the seeds),
-- and orders each level by how much search its proof took -- a rough
-- easiest-first.
-- ---------------------------------------------------------------------------

local here = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
local args = { ... }
if #args == 0 then args = arg end
local retree = false
if args[1] == "--retree" then
    retree = true
    table.remove(args, 1)
end
local out_path = assert(args[1], "usage: merge_bank.lua [--retree] <out> <parts...>")

local function transposeKey(rows)
    local t = {}
    for c = 1, #rows[1] do
        local col = {}
        for r = 1, #rows do col[r] = rows[r]:sub(c, c) end
        t[c] = table.concat(col)
    end
    local a, b = table.concat(rows, "/"), table.concat(t, "/")
    return (a < b) and a or b
end

local all, seen, dups = {}, {}, 0
for i = 2, #args do
    local part = assert(loadfile(args[i]))()
    for _, p in ipairs(part) do
        local key = p.kind .. ":" .. transposeKey(p.rows)
        if seen[key] then
            dups = dups + 1
        else
            seen[key] = true
            all[#all + 1] = p
        end
    end
end

-- --retree: rebuild every tree with the current gen_bank.lua (the positions
-- and their proofs stay; only the stored replies may change), dropping any
-- problem whose tree can no longer be built.
if retree then
    local Gen = dofile(here .. "gen_bank.lua")
    local kept, dropped = {}, 0
    for k, p in ipairs(all) do
        local tree, why = Gen.retree(p)
        if tree then
            p.tree, p.level = tree, tree.d
            kept[#kept + 1] = p
        else
            dropped = dropped + 1
            print("dropped " .. p.seed .. ": " .. tostring(why))
        end
        if k % 20 == 0 then io.stderr:write(k .. "/" .. #all .. "\n") end
    end
    all = kept
    print(string.format("retree: %d kept, %d dropped", #all, dropped))
end

table.sort(all, function(a, b)
    local la, lb = math.min(3, a.level), math.min(3, b.level)
    if la ~= lb then return la < lb end
    if a.search ~= b.search then return a.search < b.search end
    return a.seed < b.seed
end)

-- Re-serialises a tree node exactly as gen_bank.lua writes it.
local function ser(node, out)
    out[#out + 1] = "{m=" .. string.format("%q", node.m) .. ",d=" .. node.d .. ",w={"
    local keys = {}
    for k in pairs(node.w) do keys[#keys + 1] = k end
    table.sort(keys)
    for _, k in ipairs(keys) do
        local v = node.w[k]
        if v == 1 then
            out[#out + 1] = k .. "=1,"
        else
            out[#out + 1] = k .. "={r=" .. string.format("%q", v.r) .. ",n="
            ser(v.n, out)
            out[#out + 1] = "},"
        end
    end
    out[#out + 1] = "},l={"
    keys = {}
    for k in pairs(node.l) do keys[#keys + 1] = k end
    table.sort(keys)
    for _, k in ipairs(keys) do
        out[#out + 1] = k .. "=" .. string.format("%q", node.l[k]) .. ","
    end
    out[#out + 1] = "}}"
end

local f = assert(io.open(out_path, "w"))
f:write([[
-- ---------------------------------------------------------------------------
-- problems.lua -- GENERATED by gen/gen_bank.lua + gen/merge_bank.lua. Do not
-- edit by hand: every entry is proven by solver.lua, and test_bank_spec.lua
-- re-proves them all.
--
-- id     generator seed (stable key for saved progress)
-- kind   "kill" (Black attacks; walls are Black) or "live" (Black defends;
--        walls are White)
-- level  Black moves in the main line (1 Easy, 2 Medium, 3+ Hard)
-- rows   the frame, top-left corner of the board: '.' empty, 'X' Black,
--        'O' White, '#' wall (attacker's living stones)
-- tree   Black-to-play node: m = main (hint) move, d = moves to the end of
--        the main line, w[move] = 1 (solved) or {r = White's answer,
--        n = next node}, l[move] = White's refutation ("" = pass).
--        Moves are SGF-style frame coordinates: column letter, row letter.
-- ---------------------------------------------------------------------------
return {
]])
local per_level = { 0, 0, 0 }
for _, p in ipairs(all) do
    local lvl = math.min(3, p.level)
    per_level[lvl] = per_level[lvl] + 1
    local q = {}
    for i, r in ipairs(p.rows) do q[i] = string.format("%q", r) end
    local buf = {}
    ser(p.tree, buf)
    f:write(string.format("{id=%d,kind=%q,level=%d,rows={%s},\ntree=%s},\n",
        p.seed, p.kind, p.level, table.concat(q, ","), table.concat(buf)))
end
f:write("}\n")
f:close()
print(string.format("%d problems (easy %d, medium %d, hard %d), %d duplicates dropped",
    #all, per_level[1], per_level[2], per_level[3], dups))
